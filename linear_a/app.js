// Setup event listeners
function setupEventListeners() {
    // Filter controls
    document.getElementById('siteFilter').addEventListener('change', filterInscriptions);
    document.getElementById('contextFilter').addEventListener('change', filterInscriptions);
    
    // Player controls
    document.getElementById('playBtn').addEventListener('click', () => {
        if (!isPlaying) {
            playRandomInscription();
        }
    });
    
    document.getElementById('pauseBtn').addEventListener('click', stopCurrentSound);
    document.getElementById('stopBtn').addEventListener('click', stopCurrentSound);
    document.getElementById('randomBtn').addEventListener('click', playRandomInscription);
    
    // Smooth scrolling for navigation
    document.querySelectorAll('a[href^="#"]').forEach(anchor => {
        anchor.addEventListener('click', function (e) {
            e.preventDefault();
            const target = document.querySelector(this.getAttribute('href'));
            if (target) {
                target.scrollIntoView({ behavior: 'smooth' });
            }
        });
    });
}

// Filter inscriptions
function filterInscriptions() {
    const siteFilter = document.getElementById('siteFilter').value;
    const contextFilter = document.getElementById('contextFilter').value;
    const cards = document.querySelectorAll('.inscription-card');
    
    cards.forEach(card => {
        const site = card.dataset.site;
        const context = card.dataset.context;
        
        const siteMatch = siteFilter === 'all' || site === siteFilter;
        const contextMatch = contextFilter === 'all' || context === contextFilter;
        
        if (siteMatch && contextMatch) {
            card.style.display = 'block';
            card.classList.add('fade-in');
        } else {
            card.style.display = 'none';
        }
    });
}

// Play random inscription
