// Visualize frequency on canvas
function visualizeFrequency(frequencies) {
    const canvas = document.getElementById('frequencyCanvas');
    const ctx = canvas.getContext('2d');
    
    ctx.clearRect(0, 0, canvas.width, canvas.height);
    
    const barWidth = canvas.width / frequencies.length;
    const maxFreq = Math.max(...frequencies);
    
    frequencies.forEach((freq, index) => {
        const barHeight = (freq / maxFreq) * canvas.height * 0.8;
        const x = index * barWidth;
        const y = canvas.height - barHeight;
        
        // Create gradient
        const gradient = ctx.createLinearGradient(0, y, 0, canvas.height);
        gradient.addColorStop(0, '#667eea');
        gradient.addColorStop(1, '#764ba2');
        
        ctx.fillStyle = gradient;
        ctx.fillRect(x, y, barWidth - 2, barHeight);
        
        // Add frequency label
        ctx.fillStyle = '#333';
        ctx.font = '10px Arial';
        ctx.textAlign = 'center';
        ctx.fillText(Math.round(freq) + 'Hz', x + barWidth/2, canvas.height - 5);
    });
}

