// Play inscription as sound
function playInscription(inscriptionId) {
    const inscription = analysisData.individual_analyses.find(i => i.inscription_id === inscriptionId);
    if (!inscription) return;
    
    stopCurrentSound();
    
    if (typeof Tone !== 'undefined') {
        playWithToneJS(inscription);
    } else {
        playWithWebAudio(inscription);
    }
    
    updateCurrentInscriptionDisplay(inscription);
    visualizeFrequency(inscription.individual_frequencies);
}

// Play using Tone.js
function playWithToneJS(inscription) {
    const frequencies = inscription.individual_frequencies;
    const synth = new Tone.PolySynth().toDestination();
    
    // Convert frequencies to notes
    const notes = frequencies.map(freq => Tone.Frequency(freq).toNote());
    
    // Play the chord
    synth.triggerAttackRelease(notes, "2n");
    
    // Play sequence
    const sequence = new Tone.Sequence((time, note) => {
        synth.triggerAttackRelease(note, "8n", time);
    }, notes, "4n");
    
    sequence.start();
    Tone.Transport.start();
    
    // Stop after 4 seconds
    setTimeout(() => {
        sequence.stop();
        Tone.Transport.stop();
        synth.dispose();
    }, 4000);
}

// Play using Web Audio API
function playWithWebAudio(inscription) {
    const frequencies = inscription.individual_frequencies;
    currentOscillators = [];
    
    frequencies.forEach((freq, index) => {
        setTimeout(() => {
            const oscillator = audioContext.createOscillator();
            const gainNode = audioContext.createGain();
            
            oscillator.connect(gainNode);
            gainNode.connect(audioContext.destination);
            
            oscillator.frequency.setValueAtTime(freq, audioContext.currentTime);
            oscillator.type = 'sine';
            
            gainNode.gain.setValueAtTime(0.1, audioContext.currentTime);
            gainNode.gain.exponentialRampToValueAtTime(0.01, audioContext.currentTime + 1);
            
            oscillator.start();
            oscillator.stop(audioContext.currentTime + 1);
            
            currentOscillators.push(oscillator);
        }, index * 500);
    });
    
    isPlaying = true;
    setTimeout(() => { isPlaying = false; }, frequencies.length * 500 + 1000);
}

// Stop current sound
function stopCurrentSound() {
    if (typeof Tone !== 'undefined') {
        Tone.Transport.stop();
    }
    
    currentOscillators.forEach(osc => {
        try { osc.stop(); } catch(e) {}
    });
    currentOscillators = [];
    isPlaying = false;
}

